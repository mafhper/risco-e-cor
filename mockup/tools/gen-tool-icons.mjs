// Generates `src/mockup/toolIcons.ts` from the Claude tool icons.
//
// The drawings are the single source consumed by both bands (`pro` and `kids`):
// they are not redrawn here, only transcribed. The generator exists so the
// module cannot quietly drift from the files — run it after editing an SVG:
//
//   node tools/gen-tool-icons.mjs
//
// Input: the SVGs of the Claude set (one per tool). Output: one module
// with `id`, `fill` and `d` per layer, in the file's own painting order.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const SOURCE = join(root, "..", "icones-prompts", "claude");
const TARGET = join(root, "src", "mockup", "toolIcons.ts");

/** PT file name -> the English name the app, the shelf and the spec share. */
const NAMES = {
  "lapis.svg": "pencil",
  "carvao.svg": "charcoal",
  "giz-de-cera.svg": "crayon",
  "marcador.svg": "marker",
  "pincel.svg": "brush",
  "aquarela.svg": "watercolor",
  "tinta-a-oleo.svg": "oil",
  "spray.svg": "spray",
  "nanquim.svg": "ink",
  "borracha.svg": "eraser",
  "balde-de-preenchimento.svg": "fill",
  "conta-gotas.svg": "eyedropper",
  "mais-opcoes.svg": "more",
};

/** The order the module declares: the shelf's own vocabulary. */
const ORDER = [
  "pencil",
  "charcoal",
  "crayon",
  "marker",
  "brush",
  "watercolor",
  "oil",
  "spray",
  "ink",
  "eraser",
  "fill",
  "eyedropper",
  "more",
];

const attr = (tag, name) => {
  const match = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return match ? match[1] : null;
};

/** A `d` string, checked before it becomes a TypeScript literal. */
const literal = (value, file, id) => {
  if (/[\\"\n\r]/.test(value)) {
    throw new Error(`${file}#${id}: the path data carries a character a literal cannot hold`);
  }
  return `"${value}"`;
};

const icons = {};
for (const [file, name] of Object.entries(NAMES)) {
  const text = readFileSync(join(SOURCE, file), "utf8");
  const layers = [...text.matchAll(/<path\b[^>]*>/g)].map(([tag]) => {
    const id = attr(tag, "id");
    const fill = attr(tag, "fill");
    const d = attr(tag, "d");
    if (!id || !fill || !d) throw new Error(`${file}: a path is missing id, fill or d`);
    const alpha = attr(tag, "fill-opacity");
    return {
      id,
      fill,
      ...(alpha ? { fillOpacity: Number(alpha) } : {}),
      d,
    };
  });
  if (layers.length === 0) throw new Error(`${file}: no path`);
  if (!layers.some((layer) => layer.id === "outline")) {
    throw new Error(`${file}: the contour layer is missing`);
  }
  icons[name] = layers;
}

const missing = ORDER.filter((name) => !icons[name]);
if (missing.length > 0) throw new Error(`missing icons: ${missing.join(", ")}`);

const blocks = ORDER.map((name) => {
  const layers = icons[name]
    .map((layer) => {
      const alpha =
        layer.fillOpacity === undefined ? "" : `\n      fillOpacity: ${layer.fillOpacity},`;
      return `    {
      id: "${layer.id}",
      fill: "${layer.fill}",${alpha}
      d: ${literal(layer.d, name, layer.id)},
    },`;
    })
    .join("\n");
  return `  ${name}: [
${layers}
  ],`;
}).join("\n");

const output = `// The tool icons, transcribed from the Claude set — the ONE drawing per
// tool, consumed by both bands with different tints (owner's call, 26/10).
//
// GENERATED by \`tools/gen-tool-icons.mjs\` from the source SVGs; do not edit by
// hand. The geometry is the file's own: 1024 x 1024, layers in painting order,
// \`currentColor\` where the source says so. Which layer takes the tint is decided
// by the DRAWING (its \`fill === "currentColor"\`), never by a table in the
// component: accent, graphite and the \`more\` disc follow the colour; cream, metal,
// wood, cap and nib are the material; accent-shade/accent-tint keep their black
// and white with the opacity the file declares; the outline never takes the tint.
export type ToolIconName =
${ORDER.map((name) => `  | "${name}"`).join("\n")};

export type ToolIconLayer = {
  id: string;
  fill: string;
  /** The source's \`fill-opacity\`, when it has one (shade and tint layers). */
  fillOpacity?: number;
  d: string;
};

export const TOOL_ICON_LAYERS: Record<ToolIconName, readonly ToolIconLayer[]> = {
${blocks}
};

/** Every icon the set carries, in the shelf's own order. */
export const TOOL_ICON_NAMES: readonly ToolIconName[] = [
${ORDER.map((name) => `  "${name}",`).join("\n")}
];
`;

writeFileSync(TARGET, output, "utf8");
console.log(`wrote ${TARGET} (${ORDER.length} icons, ${output.length} chars)`);
